# Reproduce the data adoctra-highlight ports from the pinned Rouge (the
# version in compatibility/rouge-version) and the reference Ruby's regexp
# engine. No Ruby code runs in adoctra. Run from the repository root:
#
#   ruby scripts/generate_rouge.rb unicode > crates/adoctra-highlight/src/regex/unicode_tables.rs
#   ruby scripts/generate_rouge.rb regex-corpus > crates/adoctra-highlight/tests/data/regex_corpus.txt
#   ruby scripts/generate_rouge.rb tokens > crates/adoctra-highlight/src/generated/tokens.rs
#   ruby scripts/generate_rouge.rb themes > crates/adoctra-highlight/src/generated/themes.rs
#   ruby scripts/generate_rouge.rb lexers > crates/adoctra-highlight/src/generated/lexers.rs
#   ruby scripts/generate_rouge.rb lexer-corpus > crates/adoctra-highlight/tests/data/lexer_corpus.txt
#
# `lexers` prints the lexers whose port is incomplete on stderr.
require 'json'
require 'strscan'

ROUGE_VERSION = File.read(File.expand_path('../compatibility/rouge-version', __dir__)).strip
gem 'rouge', ROUGE_VERSION
require 'rouge'

# Unicode properties Onigmo resolves for `\p{…}` and the POSIX brackets it
# resolves for `[[:…:]]` (Unicode semantics of a UTF-8 pattern).
# Only the names Rouge's regexps use; the engine rejects any other name.
PROPERTIES = %w[L Ll Lu Lt Lm N Nl Nd Mn Mc Pc Po Cf S Sm So Word Alpha Alnum Space
                XID_Start XID_Continue].freeze
POSIX = %w[alnum alpha digit lower upper word].freeze

def ranges chars
  chars.chunk_while { |a, b| b == a + 1 }.map { |run| [run.first, run.last] }
end

def scalars
  (0..0x10ffff).reject { |cp| cp.between?(0xd800, 0xdfff) }
end

def rust_ranges name, list
  body = list.each_slice(6).map { |slice| '    ' + slice.map { |a, b| format('(0x%x, 0x%x),', a, b) }.join(' ') }
  "pub(super) const #{name}: &[(u32, u32)] = &[\n#{body.join("\n")}\n];\n"
end

def unicode
  all = scalars.map { |cp| [cp, cp.chr(Encoding::UTF_8)] }
  out = +"// Generated by scripts/generate_rouge.rb from Ruby #{RUBY_VERSION} (Onigmo, Unicode #{RbConfig::CONFIG['UNICODE_VERSION']}).\n"
  out << "// Do not edit by hand.\n\n"
  tables = []
  PROPERTIES.each do |name|
    re = Regexp.new("\\A\\p{#{name}}\\z")
    tables << ["p:#{name}", "PROP_#{name.upcase}", ranges(all.select { |_, s| re.match?(s) }.map(&:first))]
  end
  POSIX.each do |name|
    re = Regexp.new("\\A[[:#{name}:]]\\z")
    tables << ["posix:#{name}", "POSIX_#{name.upcase}", ranges(all.select { |_, s| re.match?(s) }.map(&:first))]
  end
  tables.each { |_, const, list| out << rust_ranges(const, list) << "\n" }
  out << "pub(super) const NAMED: &[(&str, &[(u32, u32)])] = &[\n"
  tables.sort_by(&:first).each { |key, const, _| out << "    (#{key.inspect}, #{const}),\n" }
  out << "];\n\n"
  # Simple case folding as Onigmo applies it to single characters: a scalar
  # whose full fold is one other scalar.
  folds = all.filter_map do |cp, s|
    folded = s.downcase(:fold)
    [cp, folded.ord] if folded.length == 1 && folded != s
  end
  out << "/// (scalar, folded) pairs, sorted by scalar.\n"
  out << "pub(super) const FOLD: &[(u32, u32)] = &[\n"
  folds.each_slice(6) { |slice| out << '    ' << slice.map { |a, b| format('(0x%x, 0x%x),', a, b) }.join(' ') << "\n" }
  out << "];\n"
  puts out
end

# Every regexp a Rouge state rule matches with, by lexer, as the lexer
# classes build them (Regexp.union, interpolation and `(?-mix:…)` included).
def rule_regexes
  found = []
  Rouge::RegexLexer::StateDSL.prepend(Module.new do
    define_method(:rule) do |re, *rest, &blk|
      found << [Thread.current[:rouge_lexer], re] if re.is_a?(Regexp)
      super(re, *rest, &blk)
    end
  end)
  Rouge::Lexer.all.sort_by(&:tag).each do |lexer|
    next unless lexer.respond_to?(:state_definitions)

    Thread.current[:rouge_lexer] = lexer.tag
    lexer.state_definitions.each_key do |state|
      lexer.get_state(state)
    rescue StandardError, NotImplementedError
      nil # a broken upstream state (e.g. ceylon) fails at lex time too
    end
  end
  found.uniq { |tag, re| [tag, re.source, re.options] }
end

# Inputs every regexp is fingerprinted on, besides its lexer's demo: ASCII
# punctuation, line ends, Latin-1 and other case pairs, combining marks,
# supplementary scalars.
STRESS = [
  "foo_bar = 42; Baz.qux(\"s\\\"t\", 'c', `x`) # note\n",
  "  \t\r\n\n<tag a=\"1\">&amp;</tag> {x: [1, 2.5e-3, 0x1F]} // c /* d */\n",
  "\u{c9}\u{e9}\u{c0}\u{e0}\u{ff}\u{178} \u{17f}Kk\u{212a} \u{3a3}\u{3c3}\u{3c2}\u{391}\u{3b1} \u{401}\u{451} \u{df} \u{1e9e} \u{1c5} i\u{307} \u{130}\u{131} \u{fb01} \u{bd} \u{663} \u{ff12} \u{a0}\u{2028}\u0085 e\u{301} \u{1f600} \u{1d49c} \u{4e2d}\u{6587} \u{30ab}\u{30bf}\n",
  "$var @ivar @@cvar :sym %w(a b) ?c \\n <<~EOS\nEOS\n-->= <= => -> :: ... || && !=\n",
  "#!/bin/sh\n$ echo \"hi\" | grep -i h\n> prompt\nSELECT * FROM t WHERE a <> 'b';\n",
].join

def corpus
  demos = Rouge::Lexer.all.to_h { |lexer| [lexer.tag, (lexer.demo rescue '').to_s.encode('UTF-8')[0, 1200]] }
  puts ['S', JSON.generate(STRESS)].join("\t")
  regexes = rule_regexes
  regexes.map(&:first).uniq.each { |tag| puts ['D', tag, JSON.generate(demos[tag])].join("\t") }
  regexes.each do |tag, re|
    input = "#{demos[tag]}\n#{STRESS}"
    hash = 0xcbf29ce484222325
    feed = lambda do |value|
      8.times do |i|
        hash = ((hash ^ ((value >> (8 * i)) & 0xff)) * 0x100000001b3) & 0xffffffffffffffff
      end
    end
    scanner = StringScanner.new(input)
    offset = 0
    input.each_char do |char|
      scanner.pos = offset
      if (size = scanner.skip(re))
        feed.(offset)
        feed.(size)
        match = re.match(input.byteslice(offset, input.bytesize - offset))
        (1...match.size).each do |group|
          start, finish = match.byteoffset(group)
          feed.(start || 0xffffffffffffffff)
          feed.(finish || 0xffffffffffffffff)
        end
      end
      offset += char.bytesize
    end
    puts ['R', tag, re.options & 7, format('%016x', hash), JSON.generate(re.source)].join("\t")
  end
end

def rust_str value
  # Rust string literal; JSON escapes are valid Rust escapes except \u.
  JSON.generate(value).gsub(/\\u(\h{4})/) { "\\u{#{Regexp.last_match(1)}}" }
end

# Rouge's token types in definition order: the index is the Rust id.
def token_list
  Rouge::Token.cache.values
end

def const_name qualname
  qualname.gsub('.', '_').gsub(/([a-z])([A-Z])/, '\\1_\\2').upcase
end

def tokens
  out = +"// Generated by scripts/generate_rouge.rb from Rouge #{ROUGE_VERSION}. Do not edit by hand.\n\n"
  out << "use crate::token::Token;\n\n"
  out << "/// (qualname, shortname) by token id.\n"
  out << "pub(crate) const TOKENS: &[(&str, &str)] = &[\n"
  token_list.each { |tok| out << "    (#{rust_str tok.qualname}, #{rust_str tok.shortname}),\n" }
  out << "];\n\n"
  out << "/// The parent of each token (its own id for a root token).\n"
  out << "pub(crate) const PARENTS: &[u16] = &[\n"
  token_list.each { |tok| out << "    #{token_list.index(tok.parent) || token_list.index(tok)},\n" }
  out << "];\n\n"
  token_list.each_with_index do |tok, index|
    out << "pub const #{const_name tok.qualname}: Token = Token(#{index});\n"
  end
  puts out
end

# The rouge adapter's stylesheet (`Theme#render scope: 'pre.rouge'`) and the
# `<pre>` style of its inline mode, plus each token's inline rules.
def themes
  gem 'asciidoctor', File.read(File.expand_path('../compatibility/asciidoctor-version', __dir__)).strip
  require 'asciidoctor'
  require 'asciidoctor/syntax_highlighter/rouge'
  adapter = Asciidoctor::SyntaxHighlighter::RougeAdapter
  out = +"// Generated by scripts/generate_rouge.rb from Rouge #{ROUGE_VERSION}. Do not edit by hand.\n\n"
  out << "use crate::theme::ThemeData;\n\n"
  out << "pub(crate) const THEMES: &[ThemeData] = &[\n"
  Rouge::Theme.registry.keys.sort.each do |name|
    theme = Rouge::Theme.find(name).new
    base = adapter.send(:base_style, name)
    out << "    ThemeData {\n"
    out << "        name: #{rust_str name},\n"
    out << "        stylesheet: #{rust_str adapter.read_stylesheet(name)},\n"
    out << "        base_style: #{base ? "Some(#{rust_str base})" : 'None'},\n"
    out << "        inline: &[\n"
    token_list.each { |tok| out << "            #{rust_str theme.style_for(tok).rendered_rules.to_a.join(';')},\n" }
    out << "        ],\n    },\n"
  end
  out << "];\n"
  puts out
end

def lexers
  require_relative 'generate_rouge_lexers'
  source, report = RougeLexers.generate(token_list)
  puts source
  incomplete = report.reject { |_, missing| missing.empty? }
  warn "#{report.size - incomplete.size} of #{report.size} lexers ported"
  incomplete.each { |ident, missing| warn "#{ident}: #{missing.size} missing: #{missing.first(3).join('; ')}" } if ENV['VERBOSE']
end

