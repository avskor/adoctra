# Unicode properties Onigmo resolves for `\p{…}` and the POSIX brackets it
# resolves for `[[:…:]]` (Unicode semantics of a UTF-8 pattern).
# Only the names Rouge's regexps use; the engine rejects any other name.
PROPERTIES = %w[L Ll Lu Lt Lm N Nl Nd Mn Mc Pc Po Cf S Sm So Word Alpha Alnum Space
                XID_Start XID_Continue].freeze
POSIX = %w[alnum alpha digit lower upper word].freeze

def ranges chars
  chars.chunk_while { |a, b| b == a + 1 }.map { |run| [run.first, run.last] }
end

def scalars
  (0..0x10ffff).reject { |cp| cp.between?(0xd800, 0xdfff) }
end

def rust_ranges name, list
  body = list.each_slice(6).map { |slice| '    ' + slice.map { |a, b| format('(0x%x, 0x%x),', a, b) }.join(' ') }
  "pub(super) const #{name}: &[(u32, u32)] = &[\n#{body.join("\n")}\n];\n"
end

def unicode
  all = scalars.map { |cp| [cp, cp.chr(Encoding::UTF_8)] }
  out = +"// Generated by scripts/generate_rouge.rb from Ruby #{RUBY_VERSION} (Onigmo, Unicode #{RbConfig::CONFIG['UNICODE_VERSION']}).\n"
  out << "// Do not edit by hand.\n\n"
  tables = []
  PROPERTIES.each do |name|
    re = Regexp.new("\\A\\p{#{name}}\\z")
    tables << ["p:#{name}", "PROP_#{name.upcase}", ranges(all.select { |_, s| re.match?(s) }.map(&:first))]
  end
  POSIX.each do |name|
    re = Regexp.new("\\A[[:#{name}:]]\\z")
    tables << ["posix:#{name}", "POSIX_#{name.upcase}", ranges(all.select { |_, s| re.match?(s) }.map(&:first))]
  end
  tables.each { |_, const, list| out << rust_ranges(const, list) << "\n" }
  out << "pub(super) const NAMED: &[(&str, &[(u32, u32)])] = &[\n"
  tables.sort_by(&:first).each { |key, const, _| out << "    (#{key.inspect}, #{const}),\n" }
  out << "];\n\n"
  # Simple case folding as Onigmo applies it to single characters: a scalar
  # whose full fold is one other scalar.
  folds = all.filter_map do |cp, s|
    folded = s.downcase(:fold)
    [cp, folded.ord] if folded.length == 1 && folded != s
  end
  out << "/// (scalar, folded) pairs, sorted by scalar.\n"
  out << "pub(super) const FOLD: &[(u32, u32)] = &[\n"
  folds.each_slice(6) { |slice| out << '    ' << slice.map { |a, b| format('(0x%x, 0x%x),', a, b) }.join(' ') << "\n" }
  out << "];\n"
  puts out
end

# Every regexp a Rouge state rule matches with, by lexer, as the lexer
# classes build them (Regexp.union, interpolation and `(?-mix:…)` included).
def rule_regexes
  found = []
  Rouge::RegexLexer::StateDSL.prepend(Module.new do
    define_method(:rule) do |re, *rest, &blk|
      found << [Thread.current[:rouge_lexer], re] if re.is_a?(Regexp)
      super(re, *rest, &blk)
    end
  end)
  Rouge::Lexer.all.sort_by(&:tag).each do |lexer|
    next unless lexer.respond_to?(:state_definitions)

    Thread.current[:rouge_lexer] = lexer.tag
    lexer.state_definitions.each_key do |state|
      lexer.get_state(state)
    rescue StandardError, NotImplementedError
      nil # a broken upstream state (e.g. ceylon) fails at lex time too
    end
  end
  found.uniq { |tag, re| [tag, re.source, re.options] }
end

