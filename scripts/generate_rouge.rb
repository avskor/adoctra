# Reproduce the data adoctra-highlight ports from the pinned Rouge (the
# version in compatibility/rouge-version) and the reference Ruby's regexp
# engine. No Ruby code runs in adoctra. Run from the repository root:
#
#   ruby scripts/generate_rouge.rb unicode > crates/adoctra-highlight/src/regex/unicode_tables.rs
#   ruby scripts/generate_rouge.rb regex-corpus > crates/adoctra-highlight/tests/data/regex_corpus.txt
#   ruby scripts/generate_rouge.rb tokens > crates/adoctra-highlight/src/generated/tokens.rs
#   ruby scripts/generate_rouge.rb themes > crates/adoctra-highlight/src/generated/themes.rs
#   ruby scripts/generate_rouge.rb lexers > crates/adoctra-highlight/src/generated/lexers.rs
#   ruby scripts/generate_rouge.rb lexer-corpus > crates/adoctra-highlight/tests/data/lexer_corpus.txt
#
# `lexers` prints the lexers whose port is incomplete on stderr.
