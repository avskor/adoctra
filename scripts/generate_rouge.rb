# Ruby's token stream for every lexer's complete demo, and for the extra
# cases: FNV-1a over each token's id, value length and bytes.
def lexer_corpus
  tokens = token_list
  Rouge::Lexer.all.sort_by(&:tag).each do |lexer|
    input = (lexer.demo rescue '').to_s.encode('UTF-8')
    hash = 0xcbf29ce484222325
    feed = lambda do |value|
      8.times { |i| hash = ((hash ^ ((value >> (8 * i)) & 0xff)) * 0x100000001b3) & 0xffffffffffffffff }
    end
    begin
      lexer.new.lex(input) do |tok, val|
        feed.(tokens.index(tok))
        feed.(val.bytesize)
        val.each_byte { |byte| feed.(byte) }
      end
      puts ['L', lexer.tag, format('%016x', hash), JSON.generate(input)].join("\t")
    rescue StandardError => e
      puts ['E', lexer.tag, JSON.generate(e.message), JSON.generate(input)].join("\t")
    end
  end
  LEXER_CASES.each do |name, input|
    hash = 0xcbf29ce484222325
    feed = lambda do |value|
      8.times { |i| hash = ((hash ^ ((value >> (8 * i)) & 0xff)) * 0x100000001b3) & 0xffffffffffffffff }
    end
    Rouge::Lexer.find_fancy(name).lex(input) do |tok, val|
      feed.(tokens.index(tok))
      feed.(val.bytesize)
      val.each_byte { |byte| feed.(byte) }
    end
    puts ['C', name, format('%016x', hash), JSON.generate(input)].join("\t")
  end
  # Lexer.guesses on every demo and the extra guessing cases.
  demos = Rouge::Lexer.all.sort_by(&:tag).map { |lexer| [nil, (lexer.demo rescue '').to_s.encode('UTF-8')] }
  (demos + GUESS_CASES).each do |mimetype, source|
    tags = Rouge::Lexer.guesses(source: source, mimetype: mimetype).map(&:tag)
    puts ['G', mimetype || '-', tags.join(','), JSON.generate(source)].join("\t")
  end
end

